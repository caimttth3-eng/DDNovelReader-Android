/// 界面语言：简体中文 / 繁体中文 / 英语 / 日语 / 韩语。
/// 跟随系统语言自动匹配（zh-CN→简体，zh-TW/HK/MO→繁体，en/ja/ko→对应语言），
/// 其余语言默认英语。
enum AppLang {
  zhHans('zhHans', '简体中文', Locale('zh', 'CN')),
  zhHant('zhHant', '繁體中文', Locale('zh', 'TW')),
  en('en', 'English', Locale('en')),
  ja('ja', '日本語', Locale('ja')),
  ko('ko', '한국어', Locale('ko'));

  const AppLang(this.code, this.nativeName, this.locale);

  final String code;
  final String nativeName;
  final Locale locale;

  /// 系统语言 → 应用语言；匹配不到默认英语。
  static AppLang detect(List<Locale> locales) {
    for (final l in locales) {
      final lang = l.languageCode.toLowerCase();
      if (lang == 'zh') {
        final isHant = l.scriptCode?.toLowerCase() == 'hant' ||
            (l.countryCode != null &&
                const ['TW', 'HK', 'MO'].contains(l.countryCode!.toUpperCase()));
        return isHant ? AppLang.zhHant : AppLang.zhHans;
      }
      if (lang == 'en') return AppLang.en;
      if (lang == 'ja') return AppLang.ja;
      if (lang == 'ko') return AppLang.ko;
    }
    return AppLang.en;
  }
}

