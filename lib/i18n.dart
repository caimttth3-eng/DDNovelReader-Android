  static String t(String key, [Map<String, Object?>? args]) {
    var s = _tables[current]?[key] ?? _tables[AppLang.en]?[key] ?? key;
    if (args != null) {
      for (final e in args.entries) {
        s = s.replaceAll('{${e.key}}', '${e.value}');
      }
    }
    return s;
  }

  /// 取指定语言的翻译表（测试与校验用）。
  static Map<String, String> tableFor(AppLang lang) =>
      _tables[lang] ?? const {};
}

