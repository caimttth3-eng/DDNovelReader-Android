/// 是否是 PC 口径下的颜文字/装饰符号（Sk / So / Pc）
bool isDecorSymbolCp(int cp) {
  var lo = 0, hi = kDecorRanges.length ~/ 2 - 1;
  while (lo <= hi) {
    final mid = (lo + hi) >> 1;
    final a = kDecorRanges[mid * 2];
    final b = kDecorRanges[mid * 2 + 1];
    if (cp < a) {
      hi = mid - 1;
    } else if (cp > b) {
      lo = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}
