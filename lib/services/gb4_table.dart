/// GB18030 四字节 idx → 码位；无效/未覆盖返回 -1
int gb4CodePoint(int idx) {
  var lo = 0, hi = kGb4Segments.length ~/ 3 - 1;
  while (lo <= hi) {
    final mid = (lo + hi) >> 1;
    final s = kGb4Segments[mid * 3];
    final c = kGb4Segments[mid * 3 + 1];
    final n = kGb4Segments[mid * 3 + 2];
    if (idx < s) {
      hi = mid - 1;
    } else if (idx >= s + n) {
      lo = mid + 1;
    } else {
      return c + (idx - s);
    }
  }
  return -1;
}
